"""report.py — turn `results/latest.json` into `RESULTS.md`.

Kept separate from the measurements so the report can be re-rendered without
re-running anything:  python benchmarks/report.py
"""
from __future__ import annotations

import json
from pathlib import Path

BENCH = Path(__file__).resolve().parent

SET_LABELS = {
    "agents_main": "AGENTS.md — direct questions",
    "agents_adversarial": "AGENTS.md — paraphrased",
    "handbook_direct": "Handbook — direct questions",
    "handbook_paraphrase": "Handbook — paraphrased",
    "blind_direct": "Firmware notes — direct questions",
    "blind_paraphrase": "Firmware notes — paraphrased",
}


def _pct(value: float) -> str:
    return f"{100 * value:.1f}%"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines + [""]


def _routing_rows(sets: dict) -> list[list[str]]:
    rows = []
    for name, r in sets.items():
        old = r.get("v01")
        rows.append([
            SET_LABELS.get(name, name), r["n"],
            f"{_pct(old['hit_at_3'])} → **{_pct(r['hit_at_3'])}**" if old else _pct(r["hit_at_3"]),
            f"{_pct(old['hit_at_1'])} → **{_pct(r['hit_at_1'])}**" if old else _pct(r["hit_at_1"]),
            f"{old['mrr']:.2f} → **{r['mrr']:.2f}**" if old else f"{r['mrr']:.2f}",
        ])
    return rows


def render(results: dict) -> str:
    out: list[str] = [
        "# Benchmark results",
        "",
        f"Generated by `python benchmarks/run_benchmarks.py` for molecule "
        f"{results.get('version', '?')}. Default configuration, real embedding model "
        "(`all-MiniLM-L6-v2`), a fresh store per experiment. Nothing is mocked.",
        "",
        "Three documents are used:",
        "",
        "- **AGENTS.md** — this repo's own spec. A development set.",
        "- **Handbook** (`corpus/handbook.md`) — a made-up engineering handbook. Also a "
        "development set: ranking weights were tuned while looking at it.",
        "- **Firmware notes** (`corpus/blind_firmware.md`) — a different domain, written "
        "*after* all tuning was frozen and scored exactly once. This is the number to trust.",
        "",
        "\"Paraphrased\" questions are deliberately worded with almost none of the "
        "section's own vocabulary. `0.1 → 0.2` compares the previous release with this one "
        "on identical labels.",
        "",
    ]

    if "blind" in results:
        blind = results["blind"]
        out += ["## 1. Blind test (nothing was tuned on this)", ""]
        out += _table(["Query set", "n", "Top-3 (0.1 → 0.2)", "Top-1", "MRR"],
                      _routing_rows(blind["routing"]))
        a = blind["abstention"]
        out += [
            f"Relevance labels on the same document: {a['in_scope_answered']}/{a['in_scope']} "
            f"real questions were answered (not labelled `low`), and "
            f"{a['off_topic_refused']}/{a['off_topic']} off-topic questions were flagged `low`. "
            "The off-topic questions that slipped through were all near-domain "
            f"(for example: \"{a['off_topic_wrongly_answered'][0]}\")."
            if a["off_topic_wrongly_answered"] else
            f"Relevance labels: {a['in_scope_answered']}/{a['in_scope']} real questions "
            f"answered, {a['off_topic_refused']}/{a['off_topic']} off-topic questions flagged.",
            "",
        ]

    if "routing" in results:
        out += ["## 2. Routing accuracy on the development sets", ""]
        out += _table(["Query set", "n", "Top-3 (0.1 → 0.2)", "Top-1", "MRR"],
                      _routing_rows(results["routing"]))

    if "ablation" in results:
        out += ["## 3. What each ranking signal is worth (top-3 / top-1)", ""]
        variants = list(next(iter(results["ablation"].values())))
        rows = []
        for variant in variants:
            rows.append([variant] + [
                f"{_pct(results['ablation'][name][variant]['hit_at_3'])} / "
                f"{_pct(results['ablation'][name][variant]['hit_at_1'])}"
                for name in results["ablation"]
            ])
        out += _table(["Variant"] + [SET_LABELS.get(n, n) for n in results["ablation"]], rows)
        out += [
            "Reading it: meaning (dense) and wording (keyword) each fail alone on paraphrases; "
            "together they do not. Query expansion matters on AGENTS.md — the document its "
            "synonym clusters were first written against — and not on the handbook, which is "
            "why it is treated as a small helper rather than the main mechanism.",
            "",
        ]

    if "abstention" in results:
        out += ["## 4. Saying \"the docs do not cover this\"", ""]
        rows = [
            [name, f"{r['in_scope_answered']}/{r['in_scope']}",
             f"{r['off_topic_refused']}/{r['off_topic']}"]
            for name, r in results["abstention"].items()
        ]
        out += _table(["Document", "Real questions answered", "Off-topic flagged `low`"], rows)
        out += [
            "Clearly unrelated questions are always flagged. Questions that *sound* like the "
            "document but are not covered by it (\"what is our parental leave policy\" against "
            "an engineering handbook) often are not — a real limit of a small embedding model.",
            "",
        ]

    if "context" in results:
        c = results["context"]
        out += [
            "## 5. `mol_context`: answers per token",
            "",
            f"{c['n']} paraphrased handbook questions (full file: {c['full_file_tokens']} "
            "tokens). \"Answer recall\" = the context contains the phrase that answers the "
            "question. **Fill** is the obvious baseline: ranked chunks in order until the "
            "budget is full, text cut off at the limit.",
            "",
        ]
        rows = []
        for budget, r in c["budgets"].items():
            saved = 1 - r["compiler_mean_tokens"] / max(1, r["fill_mean_tokens"])
            rows.append([
                budget,
                f"{_pct(r['compiler_answer_recall'])} with {r['compiler_mean_tokens']} tok",
                f"{_pct(r['fill_answer_recall'])} with {r['fill_mean_tokens']} tok",
                f"{100 * saved:.0f}% fewer",
                f"{_pct(r['compiler_focus_answer_recall'])} with "
                f"{r['compiler_focus_mean_tokens']} tok",
                r["compiler_over_budget"],
            ])
        out += _table(["Budget", "`mol_context`", "Fill the budget", "Tokens",
                       "`context_excerpt=\"focus\"`", "Over budget"], rows)
        out += [
            "The compiler gives up 0–2 points of recall and spends far fewer tokens as the "
            "budget grows, because it stops when the remaining candidates are not close to the "
            "best one. It never exceeded a budget. The query-focused excerpt is not better "
            "than keeping the head of the section on this corpus, so it is off by default.",
            "",
        ]

    if "feedback" in results:
        f = results["feedback"]
        out += [
            "## 6. Feedback: learning without collateral damage",
            "",
            f"{f['votes_cast']} votes were cast while \"an agent\" worked through "
            f"{f['n']['same_question_again']} hard questions. Top-1 accuracy before and after, "
            "from the *same* votes, under query-aware feedback and under one global weight "
            "per chunk (what 0.1 did):",
            "",
        ]
        labels = {
            "same_question_again": "The same questions, asked again",
            "reworded_question": "The same needs, reworded (never seen)",
            "other_topics": "Questions about other topics",
        }
        rows = [
            [labels[k], f["n"][k], _pct(f["before"][k]["hit_at_1"]),
             f"**{_pct(f['query_aware'][k]['hit_at_1'])}**",
             _pct(f["global_weight"][k]["hit_at_1"])]
            for k in labels
        ]
        out += _table(["Tested on", "n", "Before", "Query-aware (0.2)", "Global weight (0.1)"],
                      rows)

    if "bonds" in results:
        b = results["bonds"]
        out += [
            "## 7. Bonds: two-part questions",
            "",
            f"{b['n']} questions that need two sections each. \"Complete\" = the context "
            "contains the answer to both parts.",
            "",
        ]
        rows = [
            [budget, f"{r['no_bonds']['complete']}/{b['n']}",
             f"**{r['reference_bonds']['complete']}/{b['n']}**",
             f"{r['after_cofetch_learning']['complete']}/{b['n']}"]
            for budget, r in b["budgets"].items()
        ]
        out += _table(["Budget", "Bonds off", "Cross-reference bonds",
                       "+ after co-fetch learning"], rows)

    if "savings" in results:
        s = results["savings"]
        full = s["full_file_tokens"]
        out += [
            "## 8. Token cost (every returned token counted)",
            "",
            f"{s['questions']} questions against the handbook. Loading the whole file costs "
            f"**{full} tokens**. Everything Molecule returns is counted — the table of "
            "contents, search results and chunk bodies — not just the final chunk.",
            "",
        ]
        rows = [
            [name, r["tokens_per_question"],
             f"{100 * (1 - r['tokens_per_question'] / full):.0f}%",
             f"{r['answered']}/{s['questions']}", r["tokens"], r["questions_per_full_load"]]
            for name, r in s["workflows"].items()
        ]
        out += _table(["Workflow", "Tokens per question", "Saved vs whole file, per question",
                       "Answered", f"Total for {s['questions']} questions",
                       "Questions per one whole-file load"], rows)
        out += [
            "How to read it. If the agent would otherwise load the file for each question "
            "(a new session, or a turn that re-sends it), the per-question column is the "
            "saving. If it loads the file once and keeps it for a whole conversation, the "
            "last column is the honest one: one-call `mol_context(300)` stays cheaper for "
            "about 25 questions. The step-by-step path (index → search → fetch) is *not* "
            "cheap on a file this small: the table of contents and the search results cost "
            "tokens too, and 0.1 did not count them. That is why `mol_context` exists, and "
            "why it is the recommended path. The bigger the docs, the bigger the gap: the "
            "cost per question stays flat while the whole-file cost grows.",
            "",
        ]

    if "speed" in results:
        s = results["speed"]
        ingest = s["ingest_5k_lines"]
        out += ["## 9. Speed", ""]
        rows = [
            [f"Ingest a {ingest['lines']}-line document ({ingest['chunks']} chunks)",
             f"{ingest['wall_s']} s"],
            ["Re-ingest after editing one section",
             f"{s['incremental_reingest']['wall_s']} s "
             f"({s['incremental_reingest']['re_embedded']} chunks re-embedded, "
             f"{s['incremental_reingest']['skipped']} skipped)"],
            ["Re-ingest an unchanged file", f"{1000 * s['unchanged_reingest_s']:.1f} ms"],
            [f"Search a new question ({s['search']['chunks']} chunks, embedding included)",
             f"p50 {s['search']['p50_ms']} ms · p95 {s['search']['p95_ms']} ms"],
            ["`mol_context` for a new question (embedding included)",
             f"p50 {s['context']['p50_ms']} ms · p95 {s['context']['p95_ms']} ms"],
            ["Cold start: new process → one CLI search", f"{s['cold_start_cli_search_s']} s"],
            ["Store size on disk", f"{s['store_bytes'] / 1_048_576:.1f} MB"],
        ]
        out += _table(["Operation", "Measured"], rows)
        out += ["Measured on a 4-core cloud VM (2.1 GHz Xeon), CPU only.", ""]

    return "\n".join(out).rstrip() + "\n"


def write_report(results: dict, path: Path) -> None:
    path.write_text(render(results), encoding="utf-8")


if __name__ == "__main__":
    data = json.loads((BENCH / "results" / "latest.json").read_text(encoding="utf-8"))
    write_report(data, BENCH / "RESULTS.md")
    print(f"wrote {BENCH / 'RESULTS.md'}")
